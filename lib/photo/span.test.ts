// @vitest-environment node
import { describe, it, expect } from "vitest";
import { spanText } from "./span";

/*
  확인 화면의 여행 카드는 기간을 "2026-09-13 ~ 2026-09-14" 처럼 기계가 쓰는 모양으로 적고 있었다.
  사람이 읽는 말로 적되, 같은 해·같은 달이면 겹치는 앞부분을 한 번만 적는다.
*/
describe("spanText", () => {
  it("하루면 그날 하나", () => {
    expect(spanText(["2026-09-13"])).toBe("2026년 9월 13일");
  });

  it("같은 달이면 날짜만 이어 적는다", () => {
    expect(spanText(["2026-09-13", "2026-09-14"])).toBe("2026년 9월 13일 ~ 14일");
  });

  it("달이 바뀌면 달부터 다시 적는다", () => {
    expect(spanText(["2026-08-30", "2026-09-02"])).toBe("2026년 8월 30일 ~ 9월 2일");
  });

  it("해가 바뀌면 해부터 다시 적는다", () => {
    expect(spanText(["2025-12-31", "2026-01-02"])).toBe("2025년 12월 31일 ~ 2026년 1월 2일");
  });

  it("가운데 날이 빠져 있어도 처음과 끝만 쓴다", () => {
    expect(spanText(["2026-09-13", "2026-09-14", "2026-09-17"])).toBe("2026년 9월 13일 ~ 17일");
  });

  it("앞의 영(0)은 읽는 말에 쓰지 않는다", () => {
    expect(spanText(["2026-01-05"])).toBe("2026년 1월 5일");
  });

  it("날이 없으면 빈 글", () => {
    expect(spanText([])).toBe("");
  });
});
