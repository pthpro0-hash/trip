/*
  사용법은 한 군데에만 적는다.

  도움말 화면(/help)이 여기서 읽어 간다. 예전에는 처음 온 사람에게 뜨는 안내 창도 이 글을 읽어 갔지만, 안내 창은
  없앴다 — 로그인 전 방문자에게 뜨는 환영 팝업(WelcomeDialog)이 "무엇을 해 주는 서비스인지"를 말한다.

  적는 것은 실제로 되는 것뿐이다. 안내가 화면보다 앞서 나가면 사람은
  없는 단추를 찾아 헤매고, 그때부터 안내를 믿지 않는다.

  글은 세 층으로 나눠 둔다. 한꺼번에 다 보이면 길어서 읽기도 전에 닫는다.
    요약     갈래마다 한 줄(blurb)
    목록     항목마다 제목과 한 줄 요약(title, summary) — 훑어보는 층
    상세설명 항목을 눌러야 펼쳐지는 설명(detail) — 필요한 사람만 읽는 층
  상세설명도 한 항목에 한 가지만 적는다. 길어지면 항목을 나눈다.
*/

export interface HelpStep {
  /** 무엇을 하는 단계인지. */
  title: string;
  /** 목록에 보이는 한 줄. 제목만으로 모자랄 때 무엇인지 알려 준다. */
  summary: string;
  /** 어떻게 하는지. 누르면 펼쳐진다. 한 항목에 한 가지만. */
  detail: string;
}

export interface HelpChapter {
  id: string;
  icon: string;
  title: string;
  /** 이 갈래가 무엇을 해 주는지 한 줄로. */
  blurb: string;
  /** 바로 가 볼 곳. */
  href: string;
  hrefLabel: string;
  steps: HelpStep[];
}

