/*
  일상어 ↔ 데이터에 실제로 쓰인 말을 잇는 사전.

  데이터는 공공기관이 쓴 말("해변", "테마파크")인데 사람은 자기 말로 찾는다
  ("바닷가", "놀이공원"). 그 간극만 메운다.

  넓게 잡으면 바로 망가진다. 처음엔 단풍 → 가을, 벚꽃 → 봄처럼 계절로
  넓혔다가 '벚꽃'이 41건, '단풍'이 59건이 됐다. 그 계절 태그를 단 곳이
  전부 딸려 온 것이다. 마찬가지로 템플스테이 → '사' 같은 한 글자는 이름에
  그 글자가 든 곳을 모조리 끌어온다(63건).

  그래서 규칙은 두 가지다. 뜻이 거의 1:1인 말만 넣고, 한 글자나 계절처럼
  수십 곳이 공유하는 말로는 넓히지 않는다. '벚꽃'이나 '템플스테이'처럼
  구체적인 말은 동의어 없이도 공식 소개글 색인이 제대로 찾아준다.
*/
const SYNONYMS: Record<string, string[]> = {
  바닷가: ["해변", "해수욕장"],
  해변가: ["해변", "해수욕장"],
  물놀이: ["해수욕장", "워터파크"],
  놀이공원: ["테마파크"],
  야시장: ["시장"],
  먹거리: ["시장"],
  카페: ["카페거리"],
  고궁: ["궁"],
  한옥: ["한옥마을"],
  전통마을: ["한옥마을", "민속촌"],
  트레킹: ["둘레길", "숲길", "산책로"],
  숲: ["숲길", "휴양림", "수목원"],
  식물원: ["수목원", "정원"],
  야영: ["휴양림", "캠핑"],
  전망: ["전망대"],
  해돋이: ["일출"],
  케이블카: ["케이블카", "곤돌라"],
};

/** 검색어 한 낱말을 뜻이 비슷한 말들로 넓힌다. 자기 자신은 포함하지 않는다. */
export function synonymsFor(term: string): string[] {
  return SYNONYMS[term.toLowerCase()] ?? [];
}
